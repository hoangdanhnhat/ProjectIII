package memory

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"errors"
	"fmt"
	"io"
	"os/exec"
	"time"

	"example.com/dfir-collector/internal/collector"
)

// toolOutputLimit caps the stdout/stderr text kept for the manifest; a capture
// tool can be chatty, but the error tail is what the operator needs.
const toolOutputLimit = 8 << 10

// inspectImage opens the produced file without following links, verifies it
// is a non-empty regular file under the size cap, and hashes it.
func inspectImage(path string, maxBytes int64) (*Image, error) {
	f, err := collector.SecureOpen(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	info, err := f.Stat()
	if err != nil {
		return nil, err
	}
	if !info.Mode().IsRegular() {
		return nil, errors.New("capture output is not a regular file")
	}
	if info.Size() == 0 {
		return nil, errors.New("capture tool produced an empty file")
	}
	if info.Size() > maxBytes {
		return nil, fmt.Errorf("image is %s, above the %s limit", humanBytes(info.Size()), humanBytes(maxBytes))
	}
	digest, err := hashReader(f)
	if err != nil {
		return nil, err
	}
	return &Image{Path: path, Size: info.Size(), SHA256: digest}, nil
}

func hashReader(r io.Reader) (string, error) {
	h := sha256.New()
	if _, err := io.Copy(h, r); err != nil {
		return "", err
	}
	return hex.EncodeToString(h.Sum(nil)), nil
}

// runTool executes the acquisition binary with fixed arguments and a hard
// timeout. It never uses a shell; the only variable argument is the output
// path generated by the collector.
func runTool(ctx context.Context, exe string, args []string, timeout time.Duration) RunResult {
	callCtx, cancel := context.WithTimeout(ctx, timeout)
	defer cancel()
	cmd := exec.CommandContext(callCtx, exe, args...)
	cmd.WaitDelay = 15 * time.Second
	stdout := &cappedBuffer{limit: toolOutputLimit}
	stderr := &cappedBuffer{limit: toolOutputLimit}
	cmd.Stdout = stdout
	cmd.Stderr = stderr
	err := cmd.Run()
	res := RunResult{Stdout: stdout.String(), Stderr: stderr.String()}
	if err == nil {
		return res
	}
	var exit *exec.ExitError
	switch {
	case errors.Is(callCtx.Err(), context.DeadlineExceeded):
		res.Err = fmt.Errorf("timed out after %s", timeout)
	case errors.Is(callCtx.Err(), context.Canceled):
		res.Err = context.Canceled
	case errors.As(err, &exit):
		res.ExitCode = exit.ExitCode()
		res.Err = fmt.Errorf("exit code %d", res.ExitCode)
	default:
		res.Err = err
	}
	return res
}

// cappedBuffer keeps the first limit bytes written to it and reports whether
// anything was dropped, so a runaway tool cannot flood agent memory.
type cappedBuffer struct {
	buf     []byte
	limit   int
	dropped bool
}

func (b *cappedBuffer) Write(p []byte) (int, error) {
	total := len(p)
	if room := b.limit - len(b.buf); room > 0 {
		if len(p) > room {
			p = p[:room]
			b.dropped = true
		}
		b.buf = append(b.buf, p...)
	} else {
		b.dropped = true
	}
	return total, nil
}

func (b *cappedBuffer) String() string {
	if b.dropped {
		return string(b.buf) + "…(truncated)"
	}
	return string(b.buf)
}
